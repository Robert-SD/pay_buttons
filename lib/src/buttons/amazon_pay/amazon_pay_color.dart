/// Supported color themes for Amazon Pay buttons adhering to official guidelines.
enum AmazonPayColor {
  /// Gold / Orange (`#FF9900` / `#FFC439`) - Amazon's primary checkout color.
  gold,

  /// Dark Squid Ink (`#232F3E`) - For dark themes and high-contrast checkouts.
  darkGray,

  /// Light Gray (`#E7E9EC`) with border (`#D5D9D9`) - Subtle alternative.
  lightGray,
}
